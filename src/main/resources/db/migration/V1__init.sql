-- Baseline schema for the URL shortener.
-- Existing databases created by the previous ddl-auto=update setup are baselined
-- at version 1 and then receive the incremental migration(s).

create table if not exists api_keys (
    id bigint generated by default as identity primary key,
    key_hash varchar(64) not null,
    name varchar(100) not null,
    active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    constraint uk_api_keys_key_hash unique (key_hash)
);

create table if not exists short_urls (
    id bigint generated by default as identity primary key,
    short_code varchar(16) not null,
    original_url varchar(2048) not null,
    api_key_id bigint not null,
    active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    expires_at timestamp with time zone,
    constraint uk_short_urls_short_code unique (short_code),
    constraint fk_short_urls_api_key foreign key (api_key_id) references api_keys (id)
);

create table if not exists click_events (
    id bigint generated by default as identity primary key,
    short_url_id bigint not null,
    clicked_at timestamp with time zone not null,
    referrer varchar(512),
    device_type varchar(16) not null,
    constraint fk_click_events_short_url foreign key (short_url_id) references short_urls (id) on delete cascade
);

create index if not exists idx_short_urls_expires_at on short_urls (expires_at);
create index if not exists idx_short_urls_api_key_id on short_urls (api_key_id);
create index if not exists idx_click_url_time on click_events (short_url_id, clicked_at);
create index if not exists idx_click_time on click_events (clicked_at);
